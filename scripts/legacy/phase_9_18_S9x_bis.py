# ------------------------------------------------------------
# Permutation arithmetic (1-based 9-tuples)
# ------------------------------------------------------------
def perm_inv(p):
    n = len(p)
    inv = [0] * n
    for i, v in enumerate(p):
        inv[v - 1] = i + 1
    return tuple(inv)


def perm_compose(p, q):
    """p ∘ q: i ↦ p(q(i))."""
    return tuple(p[q[i] - 1] for i in range(len(p)))


def perm_id(n=9):
    return tuple(range(1, n + 1))


def perm_order(p):
    n = len(p)
    e = perm_id(n)
    cur = p
    k = 1
    while cur != e:
        cur = perm_compose(p, cur)
        k += 1
    return k


def cycle_type(p):
    n = len(p)
    seen = [False] * n
    cycles = []
    for i in range(n):
        if seen[i]:
            continue
        c = 0
        j = i
        while not seen[j]:
            seen[j] = True
            j = p[j] - 1
            c += 1
        cycles.append(c)
    return tuple(sorted(cycles, reverse=True))


def conjugate(g, h):
    """Return h g h^{-1}."""
    return perm_compose(h, perm_compose(g, perm_inv(h)))


def commutator(a, b):
    """[a,b] = a b a^{-1} b^{-1}."""
    return perm_compose(perm_compose(a, b), perm_compose(perm_inv(a), perm_inv(b)))


def subgroup_close(gens):
    """Return the subgroup generated by gens as a frozenset of tuples."""
    elems = set([perm_id(9)])
    frontier = list(elems)
    gens = list(gens)
    while frontier:
        new_frontier = []
        for x in frontier:
            for g in gens:
                xg = perm_compose(x, g)
                if xg not in elems:
                    elems.add(xg)
                    new_frontier.append(xg)
                gx = perm_compose(g, x)
                if gx not in elems:
                    elems.add(gx)
                    new_frontier.append(gx)
        frontier = new_frontier
    return elems


