# (Y4) Block systems / orbits
# ------------------------------------------------------------
def orbits_of_subgroup(K_set, n=9):
    pts = set(range(1, n + 1))
    orbs = []
    while pts:
        x = min(pts)
        orb = set([x])
        frontier = [x]
        while frontier:
            new_f = []
            for y in frontier:
                for g in K_set:
                    z = g[y - 1]
                    if z not in orb:
                        orb.add(z)
                        new_f.append(z)
            frontier = new_f
        pts -= orb
        orbs.append(sorted(orb))
    return orbs


def is_transitive(K_set, n=9):
    return len(orbits_of_subgroup(K_set, n)) == 1


def find_block_systems(K_set, n=9):
    """All non-trivial block systems (partitions of {1..n} preserved by K).

    Returns list of partitions; orbit-equivalent blocks merged.
    """
    if not is_transitive(K_set, n):
        return []  # restrict to transitive case for cleanliness
    systems = []
    seen_systems = set()
    # For each pair (1, j), j != 1, compute the smallest block containing {1, j}
    for j in range(2, n + 1):
        block = {1, j}
        changed = True
        while changed:
            changed = False
            new_block = set(block)
            for g in K_set:
                for x in block:
                    new_block.add(g[x - 1])
            # The image g·block must be either equal to block or disjoint;
            # if not equal, take union (forces enlargement until block stable)
            for g in K_set:
                img = frozenset(g[x - 1] for x in block)
                if img != frozenset(block) and img & frozenset(block):
                    new_block |= img
                    changed = True
            if new_block != block:
                block = new_block
                changed = True
        # Now build the full system as the orbit of block under K
        full_partition = []
        used = set()
        for x in range(1, n + 1):
            if x in used:
                continue
            # Find the K-translate of block containing x
            # If x ∈ block, take block; else find g with g(b)=x for some b∈block
            for g in K_set:
                img = frozenset(g[b - 1] for b in block)
                if x in img:
                    full_partition.append(sorted(img))
                    used |= img
                    break
        full_partition_tuple = tuple(tuple(p) for p in sorted(full_partition))
        if full_partition_tuple not in seen_systems and len(block) < n:
            seen_systems.add(full_partition_tuple)
            systems.append([list(p) for p in full_partition_tuple])
    return systems


