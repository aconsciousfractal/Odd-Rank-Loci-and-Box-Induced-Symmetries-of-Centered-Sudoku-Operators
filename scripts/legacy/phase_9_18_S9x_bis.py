# (Y3) Group-theoretic invariants
# ------------------------------------------------------------
def center(K_set):
    """Z(K) = {z ∈ K : zg = gz ∀ g ∈ K}."""
    Z = []
    for z in K_set:
        if all(perm_compose(z, g) == perm_compose(g, z) for g in K_set):
            Z.append(z)
    return Z


def derived_subgroup(K_set):
    """K' = ⟨[a,b] : a,b ∈ K⟩, intersected with K (always ⊆ K since K is subgroup)."""
    K_list = list(K_set)
    comms = set()
    for a in K_list:
        for b in K_list:
            comms.add(commutator(a, b))
    # Generate subgroup from commutators (closed under composition)
    if not comms:
        return set([perm_id(9)])
    return subgroup_close(list(comms)) & K_set


def derived_series(K_set):
    series = [K_set]
    cur = K_set
    while True:
        nxt = derived_subgroup(cur)
        if len(nxt) == len(cur):
            break
        series.append(nxt)
        cur = nxt
    return series


def abelianization_order(K_set):
    """|K / K'| = |K| / |K'|."""
    Kp = derived_subgroup(K_set)
    return len(K_set) // len(Kp)


def conjugacy_classes(K_set):
    K_list = list(K_set)
    seen = set()
    classes = []
    for g in K_list:
        if g in seen:
            continue
        cls = set()
        for h in K_list:
            cls.add(conjugate(g, h))
        seen |= cls
        classes.append(cls)
    return classes


