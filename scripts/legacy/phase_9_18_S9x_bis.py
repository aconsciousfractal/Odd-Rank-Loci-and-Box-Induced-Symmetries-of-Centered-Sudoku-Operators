# (Y5) Annihilation lemma: u*^T S_M19(γ) v = 0 for γ ∈ Γ*
# ------------------------------------------------------------
def kernel_annihilation_test(L_M19, Gamma_star, u_star_8):
    """For each γ ∈ Γ*, build S_8(γ) (left version), check u*^T S_8 = 0.

    We use the LEFT side here (since side-mix in S9x was 72/72 left).
    Returns: (n_certified, n_total, max_residual_norm_inf).
    """
    n = 9
    n_total = len(Gamma_star)
    n_cert = 0
    max_res = 0
    u_arr = np.array(u_star_8, dtype=np.int64)
    for gamma in Gamma_star:
        S_full = build_S(L_M19, gamma)
        # build_S returns the 9x9 (or 8x8) sumcheck matrix. Determine
        # convention: S9x uses S_8 (8x8) after projecting by Σ=0.
        S = np.array(S_full, dtype=np.int64)
        if S.shape == (9, 9):
            # Project by removing last row+col is incorrect; use 8x8 from
            # build_S directly if available. For now, test on full 9-vec:
            u9 = np.array(u_star_8 + [-(sum(u_star_8))]
                          if len(u_star_8) == 8
                          else u_star_8, dtype=np.int64)
            res = u9 @ S
        else:
            res = u_arr @ S
        rn = int(np.max(np.abs(res)))
        if rn == 0:
            n_cert += 1
        if rn > max_res:
            max_res = rn
    return n_cert, n_total, max_res


