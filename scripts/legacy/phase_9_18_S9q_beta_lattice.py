# --------------------------------------------------------------------
# Build the orbit of v under all 725760 actions.
# --------------------------------------------------------------------

def orbit(vec):
    """Full G*-orbit of vec, as a (|orb|, 9) int array of distinct rows."""
    v = np.asarray(vec, dtype=np.int64)
    permuted = v[ACTION_IDX.astype(np.int64)]                      # (N,9)
    signed = permuted * ACTION_SIGN[:, None].astype(np.int64)      # (N,9)
    # Deduplicate rows.
    uniq = np.unique(signed, axis=0)
    return uniq


