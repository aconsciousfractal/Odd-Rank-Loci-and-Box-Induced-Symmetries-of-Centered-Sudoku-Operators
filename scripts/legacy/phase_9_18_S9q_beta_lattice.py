def main():
    print("=" * 78)
    print("Phase 9.18.S9q-β-lattice — Lattice characterization of Λ_M, Λ_{O_6}")
    print("=" * 78)
    print(flush=True)

    M_rep = (-1, -1, 0, 0, 0, 0, 0, 1, 1)
    O6_rep = (-2, -1, 0, 0, 0, 0, 0, 1, 2)

    # Build orbits.
    print("  building orb(M) …", flush=True)
    orb_M = orbit(M_rep)
    print(f"  |orb(M)| = {orb_M.shape[0]}", flush=True)
    assert orb_M.shape[0] == 756

    print("  building orb(O_6) …", flush=True)
    orb_O6 = orbit(O6_rep)
    print(f"  |orb(O_6)| = {orb_O6.shape[0]}", flush=True)
    assert orb_O6.shape[0] == 3024

    # Sanity check: every row sums to 0 (V_std).
    assert np.all(orb_M.sum(axis=1) == 0), "orb(M) not in V_std!"
    assert np.all(orb_O6.sum(axis=1) == 0), "orb(O_6) not in V_std!"
    print("  all rows are zero-sum (V_std) ✓", flush=True)

    # ---- Question 1: rank & saturation of Λ_M.
    print()
    print("-" * 78)
    print("  Q1. Rank and saturation of Λ_M")
    print("-" * 78, flush=True)
    inv_M = lattice_invariants(orb_M, "Λ_M")

    # Reference lattice A_8 = V_std ∩ Z^9: basis e_i - e_{i+1}, i=0..7.
    A8 = np.zeros((8, 9), dtype=np.int64)
    for i in range(8):
        A8[i, i] = 1
        A8[i, i + 1] = -1
    inv_A8 = lattice_invariants(A8, "A_8 (ref)")

    saturated_M = (inv_M["rank"] == 8 and
                   inv_M["elementary_divisors"] == [1] * 8)
    print(f"  Λ_M saturates V_std ∩ Z^9 ?  {saturated_M}", flush=True)

    # ---- Question 2: rank & saturation of Λ_{O_6}.
    print()
    print("-" * 78)
    print("  Q2. Rank and elementary divisors of Λ_{O_6}")
    print("-" * 78, flush=True)
    inv_O6 = lattice_invariants(orb_O6, "Λ_{O_6}")
    saturated_O6 = (inv_O6["rank"] == 8 and
                    inv_O6["elementary_divisors"] == [1] * 8)
    print(f"  Λ_{{O_6}} saturates V_std ∩ Z^9 ?  {saturated_O6}", flush=True)

    # ---- Question 3: inclusion Λ_{O_6} ⊆ Λ_M.
    print()
    print("-" * 78)
    print("  Q3. Inclusion Λ_{O_6} ⊆ Λ_M  (test on every orbit-rep)")
    print("-" * 78, flush=True)
    # If both have rank 8 and Λ_{O_6} ⊆ Λ_M, the index is finite. For
    # efficiency test only the rep U8 = O6_rep then conclude by symmetry
    # (G* acts on both Λ_M and orb(O_6), so Λ_M is G*-invariant, so
    # checking one rep suffices).
    res = reduce_in_lattice(np.array(O6_rep, dtype=np.int64), orb_M)
    print(f"  O_6_rep ∈ Λ_M ?  {res['in_lattice']}",
          flush=True)
    if not res["in_lattice"]:
        print(f"  residue = {res['residue']}", flush=True)

    # ---- Question 4: index [Λ_M : Λ_{O_6}].
    print()
    print("-" * 78)
    print("  Q4. Index [Λ_M : Λ_{O_6}]")
    print("-" * 78, flush=True)
    if res["in_lattice"]:
        idx = index_of_sublattice(orb_M, orb_O6)
        print(f"  [Λ_M : Λ_{{O_6}}] = {idx}", flush=True)
    else:
        idx = None
        print("  not a sublattice — index undefined", flush=True)

    # ---- Question 5: 3-term witness verification (§8.25.decies.1).
    print()
    print("-" * 78)
    print("  Q5. 3-term witness  U_8 = -A - B - C  with A,B,C ∈ orb(M)")
    print("-" * 78, flush=True)
    U8 = np.array((0, 0, 2, -2, 1, -1, 0, 0, 0), dtype=np.int64)
    A = np.array((0, -1, 0, 0, -1, 1, 0, 1, 0), dtype=np.int64)
    B = np.array((0, 0, -1, 1, 1, 0, 0, -1, 0), dtype=np.int64)
    C = np.array((0, 1, -1, 1, -1, 0, 0, 0, 0), dtype=np.int64)

    rows_M_set = {tuple(row.tolist()) for row in orb_M}
    A_in = tuple(A.tolist()) in rows_M_set
    B_in = tuple(B.tolist()) in rows_M_set
    C_in = tuple(C.tolist()) in rows_M_set
    print(f"  A ∈ orb(M)?  {A_in}", flush=True)
    print(f"  B ∈ orb(M)?  {B_in}", flush=True)
    print(f"  C ∈ orb(M)?  {C_in}", flush=True)
    sum_ABC = A + B + C
    print(f"  A + B + C = {list(sum_ABC)}", flush=True)
    print(f"  -U_8       = {list(-U8)}", flush=True)
    matches = bool(np.all(sum_ABC == -U8))
    print(f"  matches -U_8 ?  {matches}", flush=True)

    # ---- Final summary.
    print()
    print("=" * 78)
    print("  Summary")
    print("=" * 78)
    print(f"  rank(Λ_M)               = {inv_M['rank']}")
    print(f"  elem. div.(Λ_M)         = {inv_M['elementary_divisors']}")
    print(f"  rank(Λ_{{O_6}})           = {inv_O6['rank']}")
    print(f"  elem. div.(Λ_{{O_6}})     = {inv_O6['elementary_divisors']}")
    print(f"  Λ_M = V_std ∩ Z^9 ?     = {saturated_M}")
    print(f"  Λ_{{O_6}} ⊆ Λ_M ?         = {res['in_lattice']}")
    print(f"  [Λ_M : Λ_{{O_6}}]         = {idx}")
    print(f"  3-term witness valid ?  = {matches}")

    out = {
        "phase": "9.18.S9q-β-lattice (lattice characterization)",
        "M_rep": list(M_rep),
        "O6_rep": list(O6_rep),
        "orb_sizes": {"M": int(orb_M.shape[0]),
                      "O_6": int(orb_O6.shape[0])},
        "Lambda_M": {
            "rank": inv_M["rank"],
            "elementary_divisors": inv_M["elementary_divisors"],
            "saturates_V_std": saturated_M,
        },
        "Lambda_O6": {
            "rank": inv_O6["rank"],
            "elementary_divisors": inv_O6["elementary_divisors"],
            "saturates_V_std": saturated_O6,
        },
        "A8_reference": {
            "rank": inv_A8["rank"],
            "elementary_divisors": inv_A8["elementary_divisors"],
        },
        "inclusion_O6_in_LambdaM": bool(res["in_lattice"]),
        "index_LambdaM_over_LambdaO6": idx,
        "three_term_witness": {
            "A": list(A.tolist()), "B": list(B.tolist()),
            "C": list(C.tolist()),
            "U8": list(U8.tolist()),
            "A_in_orbM": A_in, "B_in_orbM": B_in, "C_in_orbM": C_in,
            "sum_equals_minus_U8": matches,
        },
    }

    out_path = DATA / "phase_9_18_S9q_beta_lattice.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
    print(f"\n  saved → {out_path}", flush=True)


if __name__ == "__main__":
    main()
