# Lattice tools.
# --------------------------------------------------------------------

def lattice_invariants(M_int, label):
    """Compute SNF, HNF, rank and elementary divisors of an int matrix.

    M_int: numpy int array of shape (k, 9), where rows are lattice generators.
    Returns dict with rank, elementary divisors, and a sympy HNF (upper).
    """
    print(f"  [{label}] matrix shape = {M_int.shape}", flush=True)
    M = sp.Matrix(M_int.tolist())

    t0 = time.time()
    H = hermite_normal_form(M.T)        # HNF of transpose: lattice in Z^9.
    t1 = time.time()
    print(f"  [{label}] HNF computed in {t1 - t0:.2f}s, "
          f"shape={H.shape}", flush=True)

    # Rank = number of nonzero columns of HNF.
    nonzero_cols = [j for j in range(H.shape[1])
                    if any(H[i, j] != 0 for i in range(H.shape[0]))]
    rank = len(nonzero_cols)
    print(f"  [{label}] rank = {rank}", flush=True)

    # Elementary divisors via SNF of the HNF (square sublatt).
    H_red = H[:, nonzero_cols]      # 9 × rank
    print(f"  [{label}] H_red shape = {H_red.shape}", flush=True)
    t0 = time.time()
    S = smith_normal_form(H_red)
    t1 = time.time()
    print(f"  [{label}] SNF computed in {t1 - t0:.2f}s", flush=True)
    elem_div = [int(S[i, i]) for i in range(min(S.shape))]
    elem_div = [d for d in elem_div if d != 0]
    print(f"  [{label}] elementary divisors = {elem_div}", flush=True)
    print(f"  [{label}] det of full sublatt (rank=8 expected) = "
          f"{np.prod(elem_div) if rank == 8 else 'n/a'}", flush=True)

    return {
        "rank": rank,
        "elementary_divisors": elem_div,
        "hnf": [[int(H[i, j]) for j in range(H.shape[1])]
                for i in range(H.shape[0])],
    }


def reduce_in_lattice(target_vec, generators_int):
    """Decide if target_vec ∈ Z⟨generators⟩ using HNF.

    target_vec: (9,) int array.
    generators_int: (k, 9) int array.
    Returns dict {in_lattice: bool, residue: list[int]}.
    """
    G = sp.Matrix(generators_int.tolist())
    H = hermite_normal_form(G.T)            # 9 × rank   (column HNF basis)
    # For each col of H find a pivot row.
    rank = H.shape[1]
    pivots = []
    for j in range(rank):
        for i in range(H.shape[0] - 1, -1, -1):
            if H[i, j] != 0:
                pivots.append(i)
                break
    target = sp.Matrix([int(x) for x in target_vec])
    residue = sp.Matrix(target)
    for j in reversed(range(rank)):
        i = pivots[j]
        h = H[i, j]
        # We need residue[i] divisible by h (after reducing higher-rank
        # pivots).
        if h == 0:
            continue
        q = sp.Rational(residue[i], h)
        if q.q != 1:
            return {"in_lattice": False,
                    "residue": [int(x) for x in residue]}
        residue = residue - int(q) * H[:, j]
    in_latt = all(residue[i] == 0 for i in range(9))
    return {"in_lattice": in_latt,
            "residue": [int(x) for x in residue]}


def index_of_sublattice(big_int, small_int):
    """Compute [Λ(big) : Λ(small)] when both have the same rank.

    Returns int (or None if the index is infinite, i.e. rank mismatch).
    """
    Bb = sp.Matrix(big_int.tolist())
    Bs = sp.Matrix(small_int.tolist())
    Hb = hermite_normal_form(Bb.T)
    Hs = hermite_normal_form(Bs.T)
    if Hb.shape[1] != Hs.shape[1]:
        return None
    # det(Hb) and det(Hs) both nonzero on full-rank sublatt.
    nonzero_b = [j for j in range(Hb.shape[1])
                 if any(Hb[i, j] != 0 for i in range(Hb.shape[0]))]
    nonzero_s = [j for j in range(Hs.shape[1])
                 if any(Hs[i, j] != 0 for i in range(Hs.shape[0]))]
    Hb_sq = Hb[:, nonzero_b]
    Hs_sq = Hs[:, nonzero_s]
    if Hb_sq.shape[1] != Hs_sq.shape[1]:
        return None
    Sb = smith_normal_form(Hb_sq)
    Ss = smith_normal_form(Hs_sq)
    db = 1
    for i in range(min(Sb.shape)):
        if Sb[i, i] != 0:
            db *= int(Sb[i, i])
    ds = 1
    for i in range(min(Ss.shape)):
        if Ss[i, i] != 0:
            ds *= int(Ss[i, i])
    if ds % db != 0:
        return None  # not a sub-lattice
    return ds // db


