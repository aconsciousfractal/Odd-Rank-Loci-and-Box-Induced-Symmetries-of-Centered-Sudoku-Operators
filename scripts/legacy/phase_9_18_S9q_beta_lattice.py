"""Phase 9.18.S9q-β-lattice — Lattice characterization of Λ_M, Λ_{O_6}.

β-2 (first probe of the β-thrust). Companion to α-quater.

Goal: characterize as integer lattices in V_std ∩ Z^9 = {v ∈ Z^9 : Σv_i = 0}
(rank 8) the two sublattices

    Λ_M    = Z⟨ orb(M)    ⟩,   |orb(M)|    = 756
    Λ_{O_6} = Z⟨ orb(O_6) ⟩,   |orb(O_6)| = 3024

generated by the two G*-orbits identified in §8.25.decies / §8.25.duodecies.

Concrete questions answered:

  1. Saturation:    Λ_M = V_std ∩ Z^9 = A_8-lattice ?
                    (i.e. does the orbit of M generate the whole rank-8
                    sub-lattice of integer zero-sum vectors?)
  2. Inclusion:     Λ_{O_6} ⊆ Λ_M ?  (already a lattice consequence of the
                    3-term witness U_8 = -A-B-C of §8.25.decies.1)
  3. Index:         [Λ_M : Λ_{O_6}] = ?
  4. SNF:           elementary divisors of both M-orbit and O_6-orbit
                    matrices (756×9 and 3024×9), whose Smith normal forms
                    expose the quotient lattice structure.
  5. Witness:       direct verification that the 3-term decomposition
                    U_8 = -A-B-C lies in Λ_M.

Method: build action tables for M and O_6, stack into integer matrices,
compute Hermite/Smith normal forms via sympy.matrices.normalforms.

Output: data/phase_9_18_S9q_beta_lattice.json + _output.txt
"""
